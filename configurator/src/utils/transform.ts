function csvToJson(csv: string): { timestamp: string; value: number }[] {
  return csv
    .trim()
    .split('\n')
    .slice(1)
    .map(line => {
      const [ts, val] = line.split('\t');
      return { timestamp: ts, value: parseFloat(val) };
    });
}

